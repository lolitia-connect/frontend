/// <reference path="../typings.d.ts" />
import type { InitOptions } from "i18next";
import i18n from "i18next";
import LanguageDetector from "i18next-browser-languagedetector";
import Backend from "i18next-http-backend";
import { initReactI18next } from "react-i18next";
import { startLanguageProgress } from "./navigation-progress";
import { matchSupportedLanguage as canonical } from "./request-language";

const DEFAULT_LANGUAGE = "en-US";

/** localStorage key holding the user's explicit language choice. */
export const LANGUAGE_STORAGE_KEY = "language";

let initialized = false;

/**
 * True once i18next has finished its initial settle (the `initialized` event).
 *
 * i18next emits the initial `languageChanged` BEFORE `initialized`, so this flag
 * is what stops the pinned init language from being written to storage as if it
 * were a user choice.
 */
let initSettled = false;

/**
 * Set while a "follow system" change is being applied.
 *
 * `followSystemLanguage()` deletes the stored preference and then calls
 * `changeLanguage()`, which emits `languageChanged`. Without this flag that
 * emission would immediately re-write the value we just cleared, so the
 * preference would never actually be forgotten. The next `languageChanged`
 * event consumes the flag.
 */
let suppressNextPersist = false;

/**
 * Read the browser's preferred language (localStorage first, then navigator).
 *
 * This is deliberately separate from i18next's `detection` option: detection
 * must NOT influence the hydration render (see `initializeI18n`).
 *
 * @param options.ignoreStored Skip the stored preference and read the browser
 *   only. Used by "follow system" to learn what the browser currently wants.
 */
export function detectBrowserLanguage(options?: {
  ignoreStored?: boolean;
}): string | undefined {
  if (typeof window === "undefined") return;

  // `supportedLngs` is typed as `false | readonly string[]` by i18next.
  // i18next APPENDS "cimode" to this array during init, so it must never be
  // treated as a user-selectable language.
  const rawSupported = i18n.options.supportedLngs;
  const supported: string[] = Array.isArray(rawSupported)
    ? rawSupported.filter((code) => code.toLowerCase() !== "cimode")
    : [];

  if (!options?.ignoreStored) {
    const stored = getStoredLanguage();
    const match = canonical(stored, supported);
    if (match) return match;
  }

  const candidates = window.navigator.languages?.length
    ? window.navigator.languages
    : [window.navigator.language];

  for (const candidate of candidates) {
    const match = canonical(candidate, supported);
    if (match) return match;
  }

  return;
}

/**
 * The raw stored preference, or `undefined` when the user has none.
 *
 * `undefined` is the "follow system" state: no explicit choice has been made, so
 * the browser decides on every load.
 */
export function getStoredLanguage(): string | undefined {
  if (typeof window === "undefined") return;
  try {
    const stored = window.localStorage.getItem(LANGUAGE_STORAGE_KEY);
    return stored || undefined;
  } catch {
    // localStorage can be unavailable (private mode, blocked cookies).
    return;
  }
}

/** Drop the stored preference so the next load follows the browser again. */
export function clearStoredLanguage(): void {
  if (typeof window === "undefined") return;
  try {
    window.localStorage.removeItem(LANGUAGE_STORAGE_KEY);
  } catch {
    // localStorage can be unavailable (private mode, blocked cookies).
  }
}

/**
 * Built-in label for the "follow system" option, per UI language.
 *
 * This is a MODE, not a language, and "System" alone is ambiguous next to real
 * language names — the requested wording is "System default" / 「系统默认」.
 *
 * It lives here rather than only in the locale catalogs because:
 *  - the `public/assets/locales/**` JSON files are generated by `i18next-cli`
 *    (`i18n:extract`), so hand-added keys would be overwritten on the next run;
 *  - `payment-portal` ships an EMPTY `components.json`, where a catalog-only key
 *    renders as a blank menu row;
 *  - `theme.system` means the theme setting ("System" / 「系统」), which is a
 *    different concept and must not be reused verbatim here.
 *
 * A catalog entry (`language.followSystem`) still wins when present, so this is
 * only a fallback.
 */
const FOLLOW_SYSTEM_LABELS: Record<string, string> = {
  "en-US": "System default",
  "zh-CN": "系统默认",
  "zh-TW": "系統預設",
  "zh-HK": "系統預設",
  "ja-JP": "システムの既定値",
  "ja-x-pseudo": "端末設定追従",
  "en-x-emoji": "💻🔄",
};

const FOLLOW_SYSTEM_FALLBACK = "System default";

/**
 * Resolve the "follow system" label for a UI language.
 *
 * Tries an exact (case-insensitive) match first, then the base language, so
 * "zh" or "zh-Hans-CN" still resolve to 「系统默认」.
 */
export function getFollowSystemLabel(language: string | undefined): string {
  if (!language) return FOLLOW_SYSTEM_FALLBACK;

  const lower = language.toLowerCase();
  const exact = Object.keys(FOLLOW_SYSTEM_LABELS).find(
    (code) => code.toLowerCase() === lower
  );
  if (exact) {
    return FOLLOW_SYSTEM_LABELS[exact] ?? FOLLOW_SYSTEM_FALLBACK;
  }

  const base = lower.split("-")[0];
  const byBase = Object.keys(FOLLOW_SYSTEM_LABELS).find(
    (code) => code.split("-")[0]?.toLowerCase() === base
  );
  return byBase
    ? (FOLLOW_SYSTEM_LABELS[byBase] ?? FOLLOW_SYSTEM_FALLBACK)
    : FOLLOW_SYSTEM_FALLBACK;
}

/**
 * Initialise i18next.
 *
 * **Deterministic on purpose.** The initial language is always `fallbackLng`
 * unless the caller passes one explicitly, so the prerendered HTML and React's
 * first client render produce identical markup. Letting `LanguageDetector` pick
 * a language here caused a hydration mismatch: the server rendered English while
 * the client's hydration render used the stored language.
 *
 * Detection happens after hydration instead — see `applyDetectedLanguage()`,
 * which `LanguageProvider` calls from an effect.
 *
 * SSR-safe: the HTTP backend and the detector are browser-only, so they are
 * registered only on the client. `initReactI18next` is registered on both sides
 * so `useTranslation()` finds an instance while prerendering.
 *
 * Idempotent: repeated calls (React strict mode, Fast Refresh, multiple mounts)
 * are no-ops after the first.
 */
export function initializeI18n(i18nConfig?: InitOptions) {
  if (initialized) return i18n;
  initialized = true;

  const isBrowser = typeof window !== "undefined";
  const { lng, ...rest } = i18nConfig ?? {};

  // Browser-only plugins: locale JSON over HTTP, and the detector used later by
  // applyDetectedLanguage() (i18next's detector also persists to localStorage).
  if (isBrowser) {
    i18n.use(Backend).use(LanguageDetector);
  }

  // Register the persistence listeners BEFORE `init()`.
  //
  // Regression: these used to be attached after `init()` returned, which broke
  // persistence entirely. When the caller bundles `resources` (all three apps
  // pass `fallbackResources` for hydration determinism), i18next runs `load()`
  // SYNCHRONOUSLY inside `init()` (see `if (this.options.resources ||
  // !this.options.initAsync)` in i18next's `init`). The `initialized` event had
  // therefore already fired by the time the listener was attached, so
  // `initSettled` never became `true` and the guard below rejected every write —
  // a chosen language was never persisted. Attaching first works for both the
  // synchronous and the asynchronous paths.
  if (isBrowser) {
    initSettled = false;
    i18n.on("initialized", () => {
      initSettled = true;
    });
    i18n.on("languageChanged", (lng) => {
      // The initial `languageChanged` fires during init, BEFORE `initialized`.
      // Persisting it would overwrite the user's saved choice with the pinned
      // hydration language on every load.
      if (!initSettled) return;
      // "Follow system" deliberately clears the preference; do not write back
      // the language it re-applied.
      if (suppressNextPersist) {
        suppressNextPersist = false;
        return;
      }
      try {
        window.localStorage.setItem(LANGUAGE_STORAGE_KEY, lng);
      } catch {
        // localStorage can be unavailable (private mode, blocked cookies).
      }
    });
  }

  i18n
    // Pass the i18n instance to react-i18next
    .use(initReactI18next)
    // For all options read: https://www.i18next.com/overview/configuration-options
    .init({
      // Defaults — callers may override any of these (see `...rest` below).
      fallbackLng: DEFAULT_LANGUAGE,
      supportedLngs: ["en-US", "zh-CN", "zh-TW", "zh-HK", "ja-JP"],

      // Interpolation configuration
      interpolation: {
        escapeValue: false, // React already escapes
      },

      // HTTP backend configuration.
      //
      // The loadPath MUST be root-absolute. It used to be
      // `assets/locales/{{lng}}/{{ns}}.json`, which the browser resolves against
      // the CURRENT page URL: on `/` that is `/assets/...` (works), but on a
      // nested route such as `/purchasing/order` it becomes
      // `/purchasing/assets/locales/...` → 404. The language switch then changed
      // `i18n.language` while every non-fallback namespace failed to load, so the
      // UI kept rendering the fallback (English) text — the reported "does not
      // follow the browser" symptom. Verified against the running dev server:
      // `/assets/locales/zh-CN/components.json` → 200, but
      // `/purchasing/assets/locales/zh-CN/main.json` → 404.
      backend: {
        loadPath: "/assets/locales/{{lng}}/{{ns}}.json",
        crossDomain: false,
        withCredentials: false,
        allowMultiLoading: true,
      },

      // Detection configuration. Read-only: `caches` is intentionally EMPTY.
      //
      // i18next-browser-languagedetector persists the active language when
      // `caches` is set. Because init pins `lng` for hydration determinism, that
      // would write the PINNED language over the user's saved choice on every
      // load — a saved "zh-CN" got silently reset to "en-US". Persistence is
      // handled explicitly by the `languageChanged` listener registered above.
      detection: {
        order: ["localStorage", "navigator", "htmlTag"],
        lookupLocalStorage: LANGUAGE_STORAGE_KEY,
        caches: [],
      },

      defaultNS: "components",
      ns: [],

      // Lets `resources` (bundled fallback language) coexist with the HTTP
      // backend that loads every other language on demand. Without this, i18next
      // treats the bundled namespaces as authoritative and skips the backend.
      partialBundledLanguages: true,

      react: {
        useSuspense: true,
      },

      // Caller configuration wins over the defaults above. This must stay AFTER
      // them: an earlier revision spread it first, so the hardcoded defaults
      // silently clobbered callers' `ns`, `defaultNS` and `react.useSuspense`
      // (payment-portal's `ns: ["app", "components"]` collapsed to `[]`).
      ...rest,

      // Deterministic first paint: the initial language is pinned so the server
      // HTML and React's hydration render match. Applied last (and `lng` is
      // destructured out of `rest`, so the caller's value is preserved) because
      // letting the detector choose here caused a hydration mismatch.
      lng: (lng as string) ?? DEFAULT_LANGUAGE,
    });

  if (isBrowser) {
    // Belt and braces: if a future revision reorders the listeners, the flag is
    // still correct once init has completed.
    if (i18n.isInitialized) initSettled = true;
    window.i18n = i18n;
  }

  return i18n;
}

/** Keep server renders isolated while retaining one browser instance for navigation. */
export function createI18nInstance(config: InitOptions) {
  if (typeof window !== "undefined") return initializeI18n(config);

  const instance = i18n.createInstance();
  instance.use(initReactI18next).init({
    defaultNS: "components",
    fallbackLng: DEFAULT_LANGUAGE,
    interpolation: { escapeValue: false },
    ...config,
    initAsync: false,
  });
  return instance;
}

function changeLanguageWithProgress(lng: string) {
  let settled = false;
  const change = i18n.changeLanguage(lng, () => {
    settled = true;
  });
  // Bundled and previously loaded translations complete synchronously.
  return settled ? change : change.finally(startLanguageProgress());
}

/**
 * Run `changeLanguage` without letting the persistence listener record it.
 *
 * Both "adopt the browser's language after mount" and "follow system" must apply
 * a language WITHOUT creating a stored preference. Persisting there is what used
 * to turn "follow the browser" into a silent permanent pin: on a fresh load with
 * nothing stored we applied the browser language, and the write then made it look
 * like an explicit choice, so later browser-language changes had no effect.
 *
 * `changeLanguage` emits `languageChanged` synchronously before its promise
 * resolves, so the flag is consumed by that emission. `finally` clears it again in
 * case nothing was emitted (i18next resolves without emitting when the change is a
 * no-op), which would otherwise leak the suppression onto the next — genuine —
 * user-driven change.
 */
async function changeLanguageWithoutPersist(
  lng: string,
  showProgress?: boolean
): Promise<void> {
  suppressNextPersist = true;
  try {
    await (showProgress
      ? changeLanguageWithProgress(lng)
      : i18n.changeLanguage(lng));
  } finally {
    suppressNextPersist = false;
  }
}

/**
 * Parameters for {@link applyDetectedLanguage}.
 */
export interface ApplyDetectedLanguageOptions {
  /** Skip the stored preference and read the browser only (used by "follow system"). */
  ignoreStored?: boolean;
  /** Show the top progress bar if translation files need to load. */
  showProgress?: boolean;
}

/**
 * Switch to the detected language. MUST be called after mount (from an effect),
 * never during render — running it during render reintroduces the hydration
 * mismatch this design exists to prevent.
 *
 * Persistence is intentionally NOT triggered: this is the "follow the
 * environment" path, so storing its result would defeat "follow system" (and
 * would silently pin a fresh visitor to whatever their browser happened to
 * prefer on their first visit).
 *
 * Returns the applied language, or `undefined` when nothing changed.
 */
export function applyDetectedLanguage(
  options?: ApplyDetectedLanguageOptions
): string | undefined {
  if (typeof window === "undefined") return;

  const detected = detectBrowserLanguage({
    ignoreStored: options?.ignoreStored,
  });
  if (!detected) return;

  // `resolvedLanguage` is only set once i18next's (async) init has settled, so
  // fall back to the configured `lng`. Without this, an early call would see
  // `undefined`, treat the pinned language as a change, and issue a redundant
  // `changeLanguage`.
  const current =
    i18n.resolvedLanguage ?? (i18n.options.lng as string | undefined);

  if (detected === current) return;

  // Fire and forget: callers are render effects or event handlers.
  changeLanguageWithoutPersist(detected, options?.showProgress);
  return detected;
}

/**
 * Return to "follow system": forget the explicit choice and re-apply whatever
 * the browser currently prefers.
 *
 * Deliberately does not write to storage — see `applyDetectedLanguage`. The
 * stored key is removed (not set to a sentinel) so "never chosen" and "reset to
 * system" are the same state, and the next load detects from scratch.
 *
 * Returns the language that was applied, or `undefined` when the browser
 * preference is unsupported/none (the pinned fallback stays in effect).
 */
export function followSystemLanguage(): string | undefined {
  if (typeof window === "undefined") return;

  clearStoredLanguage();
  return applyDetectedLanguage({ ignoreStored: true, showProgress: true });
}

/**
 * Record an explicit choice: switch language AND persist it.
 *
 * This is the only path that creates a stored preference, which is what makes the
 * choice survive a reload and makes it distinguishable from "follow system".
 */
export async function setLanguagePreference(lng: string): Promise<void> {
  await changeLanguageWithProgress(lng);
  // `changeLanguage` emits `languageChanged`, which the listener persists. Write
  // explicitly as well so the choice is still recorded if the event was skipped
  // (e.g. an identical language with no emission).
  persistLanguage(lng);
}

/** Write the stored preference, ignoring storage availability errors. */
function persistLanguage(lng: string): void {
  if (typeof window === "undefined") return;
  try {
    window.localStorage.setItem(LANGUAGE_STORAGE_KEY, lng);
  } catch {
    // localStorage can be unavailable (private mode, blocked cookies).
  }
}
